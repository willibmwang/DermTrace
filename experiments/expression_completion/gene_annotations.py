"""Read and verify gene identifiers stored inside existing Parquet files.

Ordinary pandas/Arrow reads keep their original values, labels and layout.
No expression table is generated by this helper.
"""
from pathlib import Path
import hashlib
import json
import zlib

import pyarrow.parquet as pq

SCHEMA_KEY = b"dermtrace:gene_annotations:v1"
FIELD_KEY = b"dermtrace:gene_annotation:v1"


def prefix_sha256(path, byte_count):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        remaining = byte_count
        while remaining:
            block = f.read(min(1048576, remaining))
            if not block:
                raise ValueError("File is shorter than its recorded original bytes.")
            h.update(block)
            remaining -= len(block)
    return h.hexdigest()


def read_gene_annotations(path):
    schema = pq.read_schema(path)
    encoded = (schema.metadata or {}).get(SCHEMA_KEY)
    if encoded is None:
        raise ValueError("This file has no embedded DermTrace gene annotations.")
    header = json.loads(zlib.decompress(encoded))
    if header["gene_axis"] == "columns":
        genes = [json.loads(field.metadata[FIELD_KEY]) for field in schema
                 if field.metadata and FIELD_KEY in field.metadata]
    else:
        genes = header.pop("genes")
    return {**header, "genes": genes}


def verify_preserved_original(path):
    annotation = read_gene_annotations(path)
    matches = prefix_sha256(path, annotation["original_file_size"]) == annotation["original_file_sha256"]
    if not matches:
        raise ValueError("The original file prefix no longer matches its recorded checksum.")
    return True
