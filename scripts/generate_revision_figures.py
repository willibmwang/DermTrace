"""Generate publication and website figures from the versioned revision report."""
import json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'results/reviewer_revision/figures'
WEB=ROOT/'website/assets/images'
NARRATIVE=ROOT/'results/reviewer_revision/narrative_audit'
# Validated pair (dataviz validator: chroma, CVD and normal-vision separation, contrast on white).
PRIMARY,FAIL='#2a78d6','#c2532f'
INK,MUTED,GRID='#1f2933','#5b6670','#d9dde1'

def save(fig,name,website_name=None):
    for suffix in ['svg','png','pdf']:
        fig.savefig(OUT/f'{name}.{suffix}',dpi=180,bbox_inches='tight',facecolor='white')
        if website_name:fig.savefig(WEB/f'{website_name}.{suffix}',dpi=180,bbox_inches='tight',facecolor='white')
    plt.close(fig)

def main():
    OUT.mkdir(parents=True,exist_ok=True);WEB.mkdir(parents=True,exist_ok=True)
    report=json.loads((ROOT/'results/reviewer_revision/evaluation.json').read_text())
    primary=report['primary'];secondary=report['post_hoc_seven_study_sensitivity']
    plt.rcParams.update({'font.family':'DejaVu Sans','font.size':10,'axes.spines.top':False,'axes.spines.right':False})
    rows=primary['folds']
    fig,ax=plt.subplots(figsize=(12,5))
    colors=[FAIL if r['accession']=='GSE173900' else PRIMARY for r in rows]
    ax.bar(range(len(rows)),[r['macro_f1'] for r in rows],color=colors,width=.66)
    ax.axhline(primary['mean_macro_f1'],color='#192e40',lw=2,linestyle='--',label=f"All-study mean: {primary['mean_macro_f1']:.3f}")
    ax.set_xticks(range(len(rows)),[r['accession']+'\n'+('donors' if r['grain']=='donor' else 'profiles') for r in rows],rotation=20,ha='right')
    for i,r in enumerate(rows):ax.text(i,r['macro_f1']+.015,f"{r['macro_f1']:.3f}",ha='center',fontsize=10)
    ax.set_ylim(0,1.14);ax.set_ylabel('Macro F1 (donor/sample rule)')
    ax.set_title('All eight development studies remain in the primary evaluation',loc='left',pad=22,fontweight='bold')
    ax.legend(loc='upper left',bbox_to_anchor=(0,1.08),frameon=False)
    ax.grid(axis='y',alpha=.18);ax.set_axisbelow(True)
    fig.text(.02,-.10,'Historical nested LOSO ensemble. GSE173900 is an observed study failure.\nThe 0.918 seven-study result is a post hoc sensitivity analysis, not the primary estimate.',fontsize=10)
    fig.tight_layout();save(fig,'all_study_loso','keloidbench-loso-journal')
    fig,axes=plt.subplots(1,4,figsize=(12,3.2))
    cards=[('Primary macro F1',f"{primary['mean_macro_f1']:.3f}",'8 studies · 101 profiles'),
           ('Worst-study macro F1',f"{primary['worst_macro_f1']:.3f}",'GSE173900 included'),
           ('Pooled sample accuracy',f"{primary['pooled_accuracy']:.1%}",f"{primary['pooled_correct']}/{primary['n_profiles']} profiles"),
           ('Post hoc subset F1',f"{secondary['mean_macro_f1']:.3f}",'7 studies · outcome-selected')]
    for ax,(title,value,note) in zip(axes,cards):
        ax.axis('off');ax.text(0,.85,title,fontsize=11,color='#314655');ax.text(0,.43,value,fontsize=33,fontweight='bold',color=PRIMARY);ax.text(0,.18,note,fontsize=10,color='#5b6670')
    fig.suptitle('KeloidBench: full-cohort evidence and its limits',x=.015,ha='left',fontweight='bold',fontsize=16)
    fig.text(.015,.02,'Primary metric: equal-study donor/sample macro F1. The historical ensemble differs from the live demonstration model.',fontsize=9)
    fig.tight_layout(rect=(0,.12,1,.9));save(fig,'results_overview','keloidbench-results')
    table=pd.read_csv(ROOT/'results/reviewer_revision/matched_summary.csv').sort_values('mean_macro_f1')
    fig,ax=plt.subplots(figsize=(10,7))
    colors=[FAIL if r.arm.startswith('marker_') else PRIMARY for r in table.itertuples()]
    ax.barh(table.arm,table.mean_macro_f1,color=colors)
    for i,r in enumerate(table.itertuples()):ax.text(r.mean_macro_f1+.01,i,f'{r.mean_macro_f1:.3f}',va='center')
    ax.set_xlim(0,1.05);ax.set_xlabel('Equal-study primary macro F1 · all eight studies')
    ax.set_title('Matched linear-model comparison: no general program advantage',loc='left',fontweight='bold',pad=16)
    ax.grid(axis='x',alpha=.15);ax.set_axisbelow(True)
    fig.text(.01,-.03,'Fixed features and inner-selected families are reported separately. All arms share the revision-time protocol.\nThe best fixed arm is descriptive; choosing it from these outcomes is not independent validation.',fontsize=9)
    fig.tight_layout();save(fig,'matched_markers')
    paper_cross_study(primary,secondary,pd.read_csv(ROOT/'results/reviewer_revision/matched_summary.csv'))
    narrative_audit()
    (OUT/'README.md').write_text('# Revision figures\n\nGenerated by `python scripts/generate_revision_figures.py` from `evaluation.json`, `matched_summary.csv`, and the narrative audit runs.\n\n- `paper_cross_study`: camera-ready Figure 2 replacement (all eight studies; matched marker/program comparison).\n- `narrative_audit`: camera-ready narrative audit figure (template, v1, v2).\n- `all_study_loso`, `results_overview`, `matched_markers`: larger website/report versions.\n\nAll-study bars use the documented donor/sample rule. The subset is post hoc; marker comparisons use a separate matched revision-time protocol. SVG, PNG, and PDF are supplied.\n')

def paper_style():
    plt.rcParams.update({'font.family':'DejaVu Sans','font.size':9,'axes.titlesize':9.5,'axes.labelsize':9,
        'xtick.labelsize':8.5,'ytick.labelsize':8.5,'legend.fontsize':8.5,'axes.spines.top':False,'axes.spines.right':False,
        'axes.edgecolor':MUTED,'xtick.color':MUTED,'ytick.color':INK,'axes.labelcolor':INK,'text.color':INK,
        'pdf.fonttype':42,'svg.fonttype':'none'})

def _dot_legend(ax,items,**kw):
    from matplotlib.lines import Line2D
    handles=[Line2D([],[],marker=m,ls=ls,color=c,ms=6,lw=1.2,mfc=fc) for _,c,m,ls,fc in items]
    ax.legend(handles,[i[0] for i in items],frameon=False,handletextpad=.4,columnspacing=1.4,borderaxespad=0,**kw)

def paper_cross_study(primary,secondary,matched):
    paper_style()
    t=matched.copy()
    t['family']=np.where(t.arm.str.startswith('marker')|t.arm.eq('inner_selected_marker'),'marker','program')
    names={'inner_selected_marker':'Marker, inner-selected','inner_selected_program':'Program, inner-selected'}
    t['label']=[names.get(r,(r.split('_',1)[1].replace('_',' ')) if r.startswith('marker') else r.split('_',1)[1].replace('_',' ').capitalize()) for r in t.arm]
    t['selected']=t.arm.str.startswith('inner_selected');t=t.sort_values(['selected','mean_macro_f1'])
    rows=sorted(primary['folds'],key=lambda r:r['macro_f1'])
    fig,(a,b)=plt.subplots(2,1,figsize=(5.5,6.6),gridspec_kw={'height_ratios':[len(rows)+2.2,len(t)+2.2],'hspace':.55})
    # (a) per-study results
    y=np.arange(len(rows))
    a.barh(y,[r['macro_f1'] for r in rows],height=.64,color=[FAIL if r['accession']=='GSE173900' else PRIMARY for r in rows])
    for i,r in enumerate(rows):
        a.text(1.03,i,f"{r['macro_f1']:.3f}",va='center',fontsize=8,color=INK)
    a.set_yticks(y,[r['accession'].replace('_',' ') for r in rows])
    a.axvline(primary['mean_macro_f1'],color=INK,lw=1.2,ls='--')
    a.axvline(secondary['mean_macro_f1'],color=MUTED,lw=1.2,ls=':')
    a.set_xlim(0,1.1);a.set_xticks([0,.25,.5,.75,1]);a.set_ylim(-.6,len(rows)-.4)
    a.set_xlabel('Held-out macro F1 (donor-level if class-pure, else sample-level)')
    a.set_title('(a) Nested leave-one-study-out evaluation, all eight studies',loc='left',fontweight='bold',pad=36)
    a.grid(axis='x',color=GRID,lw=.6);a.set_axisbelow(True)
    _dot_legend(a,[(f"All 8 studies, mean {primary['mean_macro_f1']:.3f} (primary)",INK,'','--','none'),
                   (f"Post hoc 7 studies, mean {secondary['mean_macro_f1']:.3f}",MUTED,'',':','none'),
                   ('Observed study failure',FAIL,'s','','auto')],
               loc='lower left',bbox_to_anchor=(0,1.01),ncol=2,fontsize=7.5,handlelength=1.6)
    # (b) matched comparison
    y=np.arange(len(t))
    for i,r in enumerate(t.itertuples()):
        c=FAIL if r.family=='marker' else PRIMARY
        b.plot([r.worst_macro_f1,r.mean_macro_f1],[i,i],color=c,lw=1.6,alpha=.45,solid_capstyle='round',zorder=1)
        b.plot(r.worst_macro_f1,i,marker='|',ms=8,mew=1.6,color=c,zorder=2)
        b.plot(r.mean_macro_f1,i,marker='o',ms=6,color=c,mec='white',mew=.8,zorder=3)
        b.text(1.03,i,f'{r.mean_macro_f1:.3f}',va='center',fontsize=8,color=INK)
    b.set_yticks(y,t.label)
    for lab in b.get_yticklabels():
        if lab.get_text() in names.values():lab.set_fontweight('bold')
    b.axhline(len(t)-2.5,color=MUTED,lw=.8)
    b.set_xlim(0,1.1);b.set_xticks([0,.25,.5,.75,1]);b.set_ylim(-.6,len(t)-.4)
    b.set_xlabel('Macro F1 across the eight held-out studies')
    b.set_title('(b) Matched protocol: single markers vs. program views',loc='left',fontweight='bold',pad=24)
    b.grid(axis='x',color=GRID,lw=.6);b.set_axisbelow(True)
    _dot_legend(b,[('Single marker',FAIL,'o','','auto'),('Program view',PRIMARY,'o','','auto'),
                   ('Mean (value at right)',MUTED,'o','','auto'),('Worst study',MUTED,'|','','auto')],
                loc='lower left',bbox_to_anchor=(0,1.01),ncol=4,fontsize=7.5)
    save(fig,'paper_cross_study')

def narrative_audit():
    import json as _json
    paper_style()
    def load(run):
        rows=[_json.loads(l) for l in (NARRATIVE/run/'responses.jsonl').read_text().splitlines()]
        return rows,_json.loads((NARRATIVE/run/'summary.json').read_text())
    det,_=load('deterministic_v1');v1,s1=load('qwen3_1_7b_v1');v2,s2=load('qwen3_8b_v2')
    english=sum(r['all_checks_pass'] and (r['raw_generation'] or '').isascii() for r in v2)
    bars=[('Deterministic template',sum(r['all_checks_pass'] for r in det),len(det),MUTED,1),
          ('v1: Qwen3-1.7B writes whole narrative',s1['all_checks_pass'],s1['n_attempts'],FAIL,1),
          ('v2: Qwen3-8B writes prose only',s2['all_checks_pass'],s2['n_attempts'],PRIMARY,1),
          ('v2, also English-only (post hoc)',english,s2['n_attempts'],PRIMARY,.5)]
    checks=[k for k in s2['checks'] if min(s2['checks'][k]['n_pass'],s1['checks'].get(k,{'n_pass':s1['n_attempts']})['n_pass'])<s1['n_attempts']]
    pretty={'factual_anchor':'Exact factual opening','numeric_fields_grounded':'No added numbers','decision_consistent':'Decision consistent',
            'abstention_disclosed':'Abstention disclosed','research_use_stated':'Disclaimer at end','contribution_direction':'Direction, phrase-level',
            'contribution_role':'Direction, clause-level (new in v2)','nonempty_and_within_word_limit':'Within word limit'}
    fig,(a,b)=plt.subplots(2,1,figsize=(5.5,5.6),gridspec_kw={'height_ratios':[len(bars)+1.6,len(checks)+1.6],'hspace':.55})
    y=np.arange(len(bars))[::-1]
    for yi,(lab,n,d,c,al) in zip(y,bars):
        a.barh(yi,n/d,height=.6,color=c,alpha=al)
        a.text(n/d+.015,yi,f'{n}/{d}  ({n/d:.0%})',va='center',fontsize=8.5)
    a.set_yticks(y,[x[0] for x in bars]);a.set_xlim(0,1.28);a.set_xticks([0,.25,.5,.75,1],['0%','25%','50%','75%','100%'])
    a.set_ylim(-.6,len(bars)-.4)
    a.set_title('(a) Outputs passing all automated checks',loc='left',fontweight='bold')
    a.grid(axis='x',color=GRID,lw=.6);a.set_axisbelow(True)
    y=np.arange(len(checks))[::-1]
    for yi,k in zip(y,checks):
        r2=s2['checks'][k]['n_pass']/s2['n_attempts']
        if k in s1['checks']:
            r1=s1['checks'][k]['n_pass']/s1['n_attempts']
            b.plot([r1,r2],[yi,yi],color=GRID,lw=2,zorder=1)
            b.plot(r1,yi,'o',color=FAIL,ms=9 if abs(r1-r2)<.03 else 6.5,mfc='white',mew=1.6,zorder=2)
            label=f'{r1:.0%} → {r2:.0%}'
        else:
            label=f'v2 only: {r2:.0%}'
        b.plot(r2,yi,'o',color=PRIMARY,ms=6.5,mec='white',mew=.8,zorder=3)
        b.text(1.04,yi,label,va='center',fontsize=8,color=INK)
    b.set_yticks(y,[pretty.get(k,k) for k in checks]);b.set_xlim(-.03,1.27);b.set_ylim(-.6,len(checks)-.4)
    b.set_xticks([0,.25,.5,.75,1],['0%','25%','50%','75%','100%'])
    b.set_title('(b) Pass rate per check (checks below 100% in either run)',loc='left',fontweight='bold',pad=22)
    b.grid(axis='x',color=GRID,lw=.6);b.set_axisbelow(True)
    _dot_legend(b,[('v1 (open circle)',FAIL,'o','','white'),('v2',PRIMARY,'o','','auto')],
                loc='lower left',bbox_to_anchor=(0,1.01),ncol=2,fontsize=8)
    save(fig,'narrative_audit')

if __name__=='__main__':main()
